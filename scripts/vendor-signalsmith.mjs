// Rebuilds src/lib/mixer/vendor/signalsmith-wasm.mjs from the signalsmith-stretch
// package (MIT, Signalsmith Audio). The package only hands out an AudioWorklet
// node, and each node needs its own OfflineAudioContext; browsers stop making
// those after about 125 in one page, which froze long mixes. This keeps the
// package's WebAssembly factory (the stretcher itself, untouched) and exports
// it, so the Mixer can run the stretcher directly with no audio context.
//   node scripts/vendor-signalsmith.mjs
import { readFileSync, writeFileSync } from "node:fs";

const pkg = JSON.parse(readFileSync("node_modules/signalsmith-stretch/package.json", "utf8"));
const src = readFileSync("node_modules/signalsmith-stretch/SignalsmithStretch.mjs", "utf8");
const cut = src.indexOf("function registerWorkletProcessor");
if (cut < 0) throw new Error("signalsmith-stretch changed shape: registerWorkletProcessor not found");
const out =
  `// Generated by scripts/vendor-signalsmith.mjs from signalsmith-stretch@${pkg.version}.\n` +
  `// Signalsmith Stretch, (c) Signalsmith Audio, MIT License. Do not edit by hand.\n` +
  `/* eslint-disable */\n// @ts-nocheck\n` +
  src.slice(0, cut) +
  `\nexport default SignalsmithStretch;\n`;
writeFileSync("src/lib/mixer/vendor/signalsmith-wasm.mjs", out);
console.log(`wrote ${out.length} bytes`);
